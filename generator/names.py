def _female_surname(s: str) -> str:
    if s.endswith(("ов", "ев", "ёв", "ин", "ын")):
        return s + "а"
    return s


class NameFactory:
    def __init__(self, rng: np.random.Generator):
        self.rng = rng
        self.used: set[str] = set()

    def make(self, female_share: float = 0.1) -> str:
        for _ in range(1000):
            female = self.rng.random() < female_share
            sur = self.rng.choice(_SURNAMES_M)
            pat = self.rng.choice(_PATRONYMIC_BASE)
            if female:
                name = f"{_female_surname(sur)} {self.rng.choice(_FIRST_F)} {pat}на"
            else:
                name = f"{sur} {self.rng.choice(_FIRST_M)} {pat}ич"
            if name not in self.used:
                self.used.add(name)
                return name
        raise RuntimeError("закончились уникальные ФИО")
