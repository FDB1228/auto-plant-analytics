-- =====================================================================
--  Операционная БД автомобилестроительного предприятия (OLTP, 3НФ)
--  Схема plant - "MES-система" завода: оргструктура, персонал, изделия,
--  технологические маршруты, производство, испытания, отгрузки.
--
--  Ключевые решения:
--   * Модель изделия (product_models) и экземпляр (units) разделены.
--   * Атрибуты, свойственные только категории, хранятся в EAV-таблице,
--     а целостность "атрибут принадлежит категории модели" обеспечивается
--     составными внешними ключами, без триггеров.
--   * Вся история (бригады, руководство, лаборатории) хранится
--     периодами действия [valid_from, valid_to), пересечения запрещены
--     exclusion-ограничениями (btree_gist).
--   * Принадлежность к категории персонала (рабочий / ИТР) проверяется
--     составным FK (employee_id, staff_category): бригадир может быть только
--     рабочим, начальник участка или мастер - только ИТР.
--   * Сотрудники не удаляются физически: увольнение = termination_date.
--   * Все метки времени - timestamptz; локальное время завода - Europe/Moscow.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA IF NOT EXISTS plant;
SET search_path = plant, public;

-- ---------------------------------------------------------------------
-- 1. Оргструктура
-- ---------------------------------------------------------------------
CREATE TABLE workshops (
    workshop_id     smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(10)  NOT NULL UNIQUE,
    name            varchar(100) NOT NULL UNIQUE,
    shifts_per_day  smallint     NOT NULL DEFAULT 1 CHECK (shifts_per_day BETWEEN 1 AND 3)
);

CREATE TABLE section_types (
    section_type    varchar(10)  PRIMARY KEY,
    name            varchar(100) NOT NULL UNIQUE
);

CREATE TABLE sections (
    section_id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workshop_id     smallint     NOT NULL REFERENCES workshops,
    section_type    varchar(10)  NOT NULL REFERENCES section_types,
    code            varchar(20)  NOT NULL UNIQUE,
    name            varchar(100) NOT NULL,
    UNIQUE (workshop_id, name),
    UNIQUE (section_id, workshop_id, section_type)      -- цель составных FK
);

-- ---------------------------------------------------------------------
-- 2. Персонал
-- ---------------------------------------------------------------------
CREATE TABLE professions (
    profession_id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(100) NOT NULL UNIQUE,
    staff_category  varchar(10)  NOT NULL CHECK (staff_category IN ('worker', 'itr')),
    UNIQUE (profession_id, staff_category)
);

CREATE TABLE employees (
    employee_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personnel_no     varchar(10)  NOT NULL UNIQUE,
    full_name        varchar(150) NOT NULL,
    profession_id    smallint     NOT NULL,
    staff_category   varchar(10)  NOT NULL,
    hire_date        date         NOT NULL,
    termination_date date,
    updated_at       timestamptz  NOT NULL DEFAULT now(),
    CHECK (termination_date IS NULL OR termination_date >= hire_date),
    FOREIGN KEY (profession_id, staff_category)
        REFERENCES professions (profession_id, staff_category),
    UNIQUE (employee_id, staff_category)
);

-- Атрибуты, характерные только для рабочих
CREATE TABLE worker_details (
    employee_id     integer      PRIMARY KEY,
    staff_category  varchar(10)  NOT NULL DEFAULT 'worker' CHECK (staff_category = 'worker'),
    skill_grade     smallint     NOT NULL CHECK (skill_grade BETWEEN 1 AND 6),   -- разряд
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    FOREIGN KEY (employee_id, staff_category)
        REFERENCES employees (employee_id, staff_category) ON DELETE CASCADE
);

-- Атрибуты, характерные только для ИТР
CREATE TABLE itr_details (
    employee_id            integer     PRIMARY KEY,
    staff_category         varchar(10) NOT NULL DEFAULT 'itr' CHECK (staff_category = 'itr'),
    qualification_category varchar(20) NOT NULL
        CHECK (qualification_category IN ('без категории', 'II', 'I', 'ведущий')),
    education              varchar(150) NOT NULL,
    FOREIGN KEY (employee_id, staff_category)
        REFERENCES employees (employee_id, staff_category) ON DELETE CASCADE
);

CREATE TABLE brigades (
    brigade_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id      smallint     NOT NULL REFERENCES sections,
    name            varchar(100) NOT NULL,
    shift           varchar(10)  NOT NULL CHECK (shift IN ('day', 'night')),
    formed_date     date         NOT NULL,
    disbanded_date  date,
    CHECK (disbanded_date IS NULL OR disbanded_date > formed_date),
    UNIQUE (section_id, name),
    UNIQUE (brigade_id, section_id)
);

-- Состав бригад во времени. Рабочий одновременно состоит не более чем в одной бригаде.
CREATE TABLE brigade_memberships (
    membership_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brigade_id      integer     NOT NULL REFERENCES brigades,
    employee_id     integer     NOT NULL,
    staff_category  varchar(10) NOT NULL DEFAULT 'worker' CHECK (staff_category = 'worker'),
    valid_from      date        NOT NULL,
    valid_to        date,                                -- не включительно; NULL = по сей день
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    FOREIGN KEY (employee_id, staff_category) REFERENCES employees (employee_id, staff_category),
    EXCLUDE USING gist (employee_id WITH =, daterange(valid_from, valid_to) WITH &&)
);

-- Бригадиры выбираются из рабочих; в каждый момент у бригады один бригадир.
CREATE TABLE brigade_leaders (
    leader_period_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brigade_id      integer     NOT NULL REFERENCES brigades,
    employee_id     integer     NOT NULL,
    staff_category  varchar(10) NOT NULL DEFAULT 'worker' CHECK (staff_category = 'worker'),
    valid_from      date        NOT NULL,
    valid_to        date,
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    FOREIGN KEY (employee_id, staff_category) REFERENCES employees (employee_id, staff_category),
    EXCLUDE USING gist (brigade_id WITH =, daterange(valid_from, valid_to) WITH &&)
);

-- Руководство: начальники цехов, начальники участков и мастера назначаются из ИТР.
CREATE TABLE management_roles (
    role_code       varchar(20)  PRIMARY KEY,
    name            varchar(100) NOT NULL UNIQUE
);

CREATE TABLE management_assignments (
    assignment_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     integer     NOT NULL,
    staff_category  varchar(10) NOT NULL DEFAULT 'itr' CHECK (staff_category = 'itr'),
    role_code       varchar(20) NOT NULL REFERENCES management_roles,
    workshop_id     smallint    REFERENCES workshops,
    section_id      smallint    REFERENCES sections,
    valid_from      date        NOT NULL,
    valid_to        date,
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    CHECK (
        (role_code = 'workshop_head' AND workshop_id IS NOT NULL AND section_id IS NULL)
     OR (role_code IN ('section_head', 'master') AND section_id IS NOT NULL AND workshop_id IS NULL)
    ),
    FOREIGN KEY (employee_id, staff_category) REFERENCES employees (employee_id, staff_category),
    -- один начальник участка / цеха в каждый момент времени
    EXCLUDE USING gist (section_id WITH =, daterange(valid_from, valid_to) WITH &&)
        WHERE (role_code = 'section_head'),
    EXCLUDE USING gist (workshop_id WITH =, daterange(valid_from, valid_to) WITH &&)
        WHERE (role_code = 'workshop_head')
);

-- ---------------------------------------------------------------------
-- 3. Изделия: категории, атрибуты категорий (EAV), модели
-- ---------------------------------------------------------------------
CREATE TABLE product_categories (
    category_id     smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(20)  NOT NULL UNIQUE,
    name            varchar(100) NOT NULL UNIQUE
);

CREATE TABLE category_attributes (
    attribute_id    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     smallint     NOT NULL REFERENCES product_categories,
    code            varchar(40)  NOT NULL,
    name            varchar(100) NOT NULL,
    unit            varchar(20),
    data_type       varchar(10)  NOT NULL CHECK (data_type IN ('numeric', 'text')),
    UNIQUE (category_id, code),
    UNIQUE (attribute_id, category_id)
);

CREATE TABLE product_models (
    model_id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id       smallint      NOT NULL REFERENCES product_categories,
    workshop_id       smallint      NOT NULL REFERENCES workshops,   -- изделие собирается в своём цехе
    code              varchar(10)   NOT NULL UNIQUE,
    name              varchar(100)  NOT NULL UNIQUE,
    launch_date       date          NOT NULL,
    discontinued_date date,
    list_price_rub    numeric(14,2) NOT NULL CHECK (list_price_rub > 0),
    std_cost_rub      numeric(14,2) NOT NULL CHECK (std_cost_rub > 0),
    CHECK (std_cost_rub < list_price_rub),
    UNIQUE (model_id, category_id),
    UNIQUE (model_id, workshop_id)
);

-- Значения атрибутов: атрибут обязан принадлежать категории модели (два составных FK)
CREATE TABLE model_attribute_values (
    model_id        smallint      NOT NULL,
    category_id     smallint      NOT NULL,
    attribute_id    smallint      NOT NULL,
    value_num       numeric(12,2),
    value_text      varchar(100),
    PRIMARY KEY (model_id, attribute_id),
    FOREIGN KEY (model_id, category_id)     REFERENCES product_models (model_id, category_id),
    FOREIGN KEY (attribute_id, category_id) REFERENCES category_attributes (attribute_id, category_id),
    CHECK (num_nonnulls(value_num, value_text) = 1)
);

-- ---------------------------------------------------------------------
-- 4. Технологический маршрут (цикл работ изделия)
-- ---------------------------------------------------------------------
CREATE TABLE work_types (
    work_type_id    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(20)  NOT NULL UNIQUE,
    name            varchar(100) NOT NULL UNIQUE,
    section_type    varchar(10)  NOT NULL REFERENCES section_types,
    UNIQUE (work_type_id, section_type)
);

-- Шаг маршрута: участок обязан быть в цехе модели, тип работ - соответствовать типу участка.
CREATE TABLE route_steps (
    model_id        smallint     NOT NULL,
    step_no         smallint     NOT NULL CHECK (step_no > 0),
    workshop_id     smallint     NOT NULL,
    section_id      smallint     NOT NULL,
    section_type    varchar(10)  NOT NULL,
    work_type_id    smallint     NOT NULL,
    std_minutes     numeric(7,1) NOT NULL CHECK (std_minutes > 0),     -- норматив, мин
    PRIMARY KEY (model_id, step_no),
    FOREIGN KEY (model_id, workshop_id)                     REFERENCES product_models (model_id, workshop_id),
    FOREIGN KEY (section_id, workshop_id, section_type)     REFERENCES sections (section_id, workshop_id, section_type),
    FOREIGN KEY (work_type_id, section_type)                REFERENCES work_types (work_type_id, section_type),
    UNIQUE (model_id, step_no, section_id)
);

-- ---------------------------------------------------------------------
-- 5. Производство: экземпляры изделий и операции
-- ---------------------------------------------------------------------
CREATE TABLE units (
    unit_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_no       char(17)     NOT NULL UNIQUE,                      -- VIN / заводской номер
    model_id        smallint     NOT NULL REFERENCES product_models,
    started_at      timestamptz  NOT NULL,
    assembled_at    timestamptz,
    accepted_at     timestamptz,
    status          varchar(15)  NOT NULL
        CHECK (status IN ('in_progress', 'testing', 'accepted', 'shipped')),
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    CHECK (assembled_at IS NULL OR assembled_at > started_at),
    CHECK (accepted_at  IS NULL OR (assembled_at IS NOT NULL AND accepted_at > assembled_at)),
    UNIQUE (unit_id, model_id)
);

-- Операция = выполнение шага маршрута бригадой. attempt_no > 1 - доработка после дефекта.
CREATE TABLE operations (
    operation_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id         integer      NOT NULL,
    model_id        smallint     NOT NULL,
    step_no         smallint     NOT NULL,
    attempt_no      smallint     NOT NULL DEFAULT 1 CHECK (attempt_no >= 1),
    section_id      smallint     NOT NULL,
    brigade_id      integer      NOT NULL,
    started_at      timestamptz  NOT NULL,
    finished_at     timestamptz  NOT NULL,
    result          varchar(10)  NOT NULL CHECK (result IN ('ok', 'defect')),
    CHECK (finished_at > started_at),
    FOREIGN KEY (unit_id, model_id)             REFERENCES units (unit_id, model_id),
    FOREIGN KEY (model_id, step_no, section_id) REFERENCES route_steps (model_id, step_no, section_id),
    FOREIGN KEY (brigade_id, section_id)        REFERENCES brigades (brigade_id, section_id),
    UNIQUE (unit_id, step_no, attempt_no)
);

CREATE TABLE downtime_reasons (
    reason_code     varchar(20)  PRIMARY KEY,
    name            varchar(100) NOT NULL UNIQUE,
    is_planned      boolean      NOT NULL
);

CREATE TABLE section_downtimes (
    downtime_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id      smallint     NOT NULL REFERENCES sections,
    reason_code     varchar(20)  NOT NULL REFERENCES downtime_reasons,
    started_at      timestamptz  NOT NULL,
    ended_at        timestamptz  NOT NULL,
    CHECK (ended_at > started_at),
    EXCLUDE USING gist (section_id WITH =, tstzrange(started_at, ended_at) WITH &&)
);

-- ---------------------------------------------------------------------
-- 6. Испытательные лаборатории
-- ---------------------------------------------------------------------
CREATE TABLE labs (
    lab_id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(10)  NOT NULL UNIQUE,
    name            varchar(150) NOT NULL UNIQUE
);

-- Лаборатория обслуживает несколько цехов, цех пользуется несколькими лабораториями
CREATE TABLE lab_workshops (
    lab_id          smallint NOT NULL REFERENCES labs,
    workshop_id     smallint NOT NULL REFERENCES workshops,
    PRIMARY KEY (lab_id, workshop_id)
);

CREATE TABLE test_types (
    test_type_id    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(10)  NOT NULL UNIQUE,
    name            varchar(100) NOT NULL UNIQUE
);

-- Программа испытаний категории изделий
CREATE TABLE category_test_plan (
    category_id     smallint NOT NULL REFERENCES product_categories,
    test_type_id    smallint NOT NULL REFERENCES test_types,
    seq_no          smallint NOT NULL CHECK (seq_no > 0),
    PRIMARY KEY (category_id, test_type_id),
    UNIQUE (category_id, seq_no)
);

CREATE TABLE equipment (
    equipment_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id            smallint     NOT NULL REFERENCES labs,
    inventory_no      varchar(20)  NOT NULL UNIQUE,
    name              varchar(150) NOT NULL,
    test_type_id      smallint     REFERENCES test_types,    -- основное назначение; NULL = вспомогательное
    commissioned_date date         NOT NULL,
    decommissioned_date date,
    CHECK (decommissioned_date IS NULL OR decommissioned_date > commissioned_date),
    UNIQUE (equipment_id, lab_id)
);

-- Специалисты лабораторий (ИТР)
CREATE TABLE lab_staff (
    lab_staff_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id          smallint    NOT NULL REFERENCES labs,
    employee_id     integer     NOT NULL,
    staff_category  varchar(10) NOT NULL DEFAULT 'itr' CHECK (staff_category = 'itr'),
    valid_from      date        NOT NULL,
    valid_to        date,
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    FOREIGN KEY (employee_id, staff_category) REFERENCES employees (employee_id, staff_category),
    EXCLUDE USING gist (employee_id WITH =, daterange(valid_from, valid_to) WITH &&)
);

CREATE TABLE tests (
    test_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id         integer      NOT NULL REFERENCES units,
    test_type_id    smallint     NOT NULL REFERENCES test_types,
    attempt_no      smallint     NOT NULL DEFAULT 1 CHECK (attempt_no >= 1),
    lab_id          smallint     NOT NULL,
    workshop_id     smallint     NOT NULL,
    specialist_id   integer      NOT NULL REFERENCES employees,
    started_at      timestamptz  NOT NULL,
    finished_at     timestamptz  NOT NULL,
    result          varchar(10)  NOT NULL CHECK (result IN ('pass', 'fail')),
    CHECK (finished_at > started_at),
    FOREIGN KEY (lab_id, workshop_id) REFERENCES lab_workshops (lab_id, workshop_id),
    UNIQUE (unit_id, test_type_id, attempt_no),
    UNIQUE (test_id, lab_id)
);

-- При испытании задействуется несколько единиц оборудования - только своей лаборатории
CREATE TABLE test_equipment (
    test_id         bigint   NOT NULL,
    lab_id          smallint NOT NULL,
    equipment_id    integer  NOT NULL,
    PRIMARY KEY (test_id, equipment_id),
    FOREIGN KEY (test_id, lab_id)      REFERENCES tests (test_id, lab_id) ON DELETE CASCADE,
    FOREIGN KEY (equipment_id, lab_id) REFERENCES equipment (equipment_id, lab_id)
);

-- ---------------------------------------------------------------------
-- 7. Дефекты, обнаруженные на заводе (на линии ОТК или на испытаниях)
-- ---------------------------------------------------------------------
CREATE TABLE defect_types (
    defect_type_id  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(10)  NOT NULL UNIQUE,
    name            varchar(150) NOT NULL UNIQUE,
    section_type    varchar(10)  NOT NULL REFERENCES section_types       -- зона возникновения
);

CREATE TABLE defects (
    defect_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id             integer       NOT NULL REFERENCES units,
    defect_type_id      smallint      NOT NULL REFERENCES defect_types,
    severity            varchar(10)   NOT NULL CHECK (severity IN ('minor', 'major', 'critical')),
    detection_point     varchar(10)   NOT NULL CHECK (detection_point IN ('line', 'test')),
    detected_at         timestamptz   NOT NULL,
    operation_id        bigint        REFERENCES operations,   -- если обнаружен на линии
    test_id             bigint        REFERENCES tests,        -- если обнаружен на испытании
    origin_operation_id bigint        REFERENCES operations,   -- операция-источник (если прослежена)
    rework_minutes      numeric(7,1)  NOT NULL CHECK (rework_minutes >= 0),
    CHECK (
        (detection_point = 'line' AND operation_id IS NOT NULL AND test_id IS NULL)
     OR (detection_point = 'test' AND test_id IS NOT NULL AND operation_id IS NULL)
    )
);

-- ---------------------------------------------------------------------
-- 8. Сбыт
-- ---------------------------------------------------------------------
CREATE TABLE dealers (
    dealer_id       smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(10)  NOT NULL UNIQUE,
    name            varchar(150) NOT NULL,
    segment         varchar(30)  NOT NULL,
    region          varchar(100) NOT NULL,
    city            varchar(100) NOT NULL
);

CREATE TABLE shipments (
    shipment_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id         integer       NOT NULL UNIQUE REFERENCES units,
    dealer_id       smallint      NOT NULL REFERENCES dealers,
    shipped_at      timestamptz   NOT NULL,
    price_rub       numeric(14,2) NOT NULL CHECK (price_rub > 0)
);

-- ---------------------------------------------------------------------
-- 9. Индексы под типовые запросы и инкрементальную выгрузку в DWH
-- ---------------------------------------------------------------------
CREATE INDEX ix_sections_workshop        ON sections (workshop_id);
CREATE INDEX ix_employees_updated        ON employees (updated_at);
CREATE INDEX ix_memberships_brigade      ON brigade_memberships (brigade_id, valid_from);
CREATE INDEX ix_mgmt_section             ON management_assignments (section_id) WHERE section_id IS NOT NULL;
CREATE INDEX ix_units_model_started      ON units (model_id, started_at);
CREATE INDEX ix_units_assembled          ON units (assembled_at);
CREATE INDEX ix_units_updated            ON units (updated_at);
CREATE INDEX ix_operations_unit          ON operations (unit_id);
CREATE INDEX ix_operations_finished      ON operations (finished_at);
CREATE INDEX ix_operations_brigade_time  ON operations (brigade_id, started_at);
CREATE INDEX ix_operations_section_time  ON operations (section_id, started_at);
CREATE INDEX ix_tests_unit               ON tests (unit_id);
CREATE INDEX ix_tests_finished           ON tests (finished_at);
CREATE INDEX ix_defects_unit             ON defects (unit_id);
CREATE INDEX ix_defects_detected         ON defects (detected_at);
CREATE INDEX ix_shipments_dealer         ON shipments (dealer_id, shipped_at);
